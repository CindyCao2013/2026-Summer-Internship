#%% 转换为宽表
def interval_to_trade_day_wide(df, trading_days, value_col='IND_CODE'):
    """
    将带有 ENTRY_DT / REMOVE_DT 的区间数据转换成交易日宽表。

    参数
    ----------
    df : pd.DataFrame
        至少包含:
        - S_INFO_WINDCODE
        - ENTRY_DT
        - REMOVE_DT
        - value_col
    trading_days : array-like
        目标交易日序列
    value_col : str
        需要填充到宽表中的值列，默认是 IND_CODE

    返回
    ----------
    pd.DataFrame
        index 为交易日，columns 为股票代码，值为 value_col
    """
    trading_days = pd.DatetimeIndex(pd.to_datetime(trading_days))
    df = df[['S_INFO_WINDCODE', 'ENTRY_DT', 'REMOVE_DT', value_col]].copy()
    df['ENTRY_DT'] = pd.to_datetime(df['ENTRY_DT'])
    df['REMOVE_DT'] = pd.to_datetime(df['REMOVE_DT'])

    # 同一股票同一起始日若有重复记录，保留最后一条。
    df = df.sort_values(['S_INFO_WINDCODE', 'ENTRY_DT', 'REMOVE_DT'])
    df = df.drop_duplicates(['S_INFO_WINDCODE', 'ENTRY_DT'], keep='last')

    stock_codes = pd.Index(df['S_INFO_WINDCODE'].drop_duplicates())
    code_to_col = {code: idx for idx, code in enumerate(stock_codes)}

    res = np.empty((len(trading_days), len(stock_codes)), dtype=object)
    res[:] = np.nan

    trade_days_arr = trading_days.to_numpy(dtype='datetime64[ns]')
    left = np.searchsorted(
        trade_days_arr,
        df['ENTRY_DT'].to_numpy(dtype='datetime64[ns]'),
        side='left'
    )
    right = np.searchsorted(
        trade_days_arr,
        df['REMOVE_DT'].to_numpy(dtype='datetime64[ns]'),
        side='right'
    )

    col_idx = df['S_INFO_WINDCODE'].map(code_to_col).to_numpy()
    values = df[value_col].to_numpy()

    for col, value, start_idx, end_idx in zip(col_idx, values, left, right):
        if start_idx < end_idx:
            res[start_idx:end_idx, col] = value

    return pd.DataFrame(res, index=trading_days, columns=stock_codes)


#%% 行业数据预热
def preheat_ind_data(startDay, endDay, preheat = True):

    startDay_str = startDay.strftime('%Y.%m.%d')
    endDay_str = endDay.strftime('%Y.%m.%d')
    s = ddb.session()
    s.connect(**DATA_DB_CONN)
    s.run(f'''A_stocks_ind=select * from loadTable('dfs://WIND.ASHAREINDUSTRIESCLASSCITICS', 'data') 
              update A_stocks_ind set REMOVE_DT=REMOVE_DT.nullFill(2100.12.31)
              A_stocks_ind = select S_INFO_WINDCODE, CITICS_IND_CODE as IND_CODE,ENTRY_DT,REMOVE_DT from A_stocks_ind 
              where ENTRY_DT <= {endDay_str} and REMOVE_DT >= {startDay_str}''')
    A_stocks_ind = s.run('A_stocks_ind')

    # 取前4位并填充0到16位, 这代表1级行业分类
    A_stocks_ind['IND_CODE'] = A_stocks_ind['IND_CODE'].str.slice(0, 4).str.ljust(16, '0')

    # IND_CODE to IND_NAME
    A_stocks_ind['IND_NAME'] = A_stocks_ind['IND_CODE'].map(CITICS_IND_CODE_DICT)
    tradingDays = Factor_Dev_Lib.get_TradingDay(startDay, endDay)

    A_stocks_ind_wide = interval_to_trade_day_wide(
        A_stocks_ind,
        tradingDays,
        value_col='IND_CODE'
    )

    if preheat:
        s.upload({'IND_DATA_CITICS': A_stocks_ind_wide.reset_index()})
        s.run('share IND_DATA_CITICS as PREHEAT_IND_DATA_CITICS')


    s.close()

    return A_stocks_ind_wide






