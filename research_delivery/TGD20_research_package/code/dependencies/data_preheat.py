def preheat_ret_matrix(startDay, endDay,index):

    """
    预热收益率矩阵
    参数:
    startDay: 开始日期
    endDay: 结束日期
    index: 指数代码, 主要是中证2000 000852.SH, 中证1000 932000.CSI
    """

    startDay_str = startDay.strftime('%Y.%m.%d')
    endDay_str = endDay.strftime('%Y.%m.%d')

    s = ddb.session()
    s.connect(**DATA_DB_CONN)
    s.run(intraday_lib.ddb_functions)

    if index == "932000.CSI":
        share_name = 'PREHEAT_RET_MATRIX_ZZ2000'
    elif index == "000852.SH":
        share_name = 'PREHEAT_RET_MATRIX_ZZ1000'
    else:
        share_name = f'PREHEAT_RET_MATRIX_{index.replace(".","_")}'
    
    sql_script = f'''
    startDay = {startDay_str}
    endDay = {endDay_str}
    index = "{index}"
    stock_vector = get_stock_pool(startDay, endDay, index,pure_stock = true)

    days_vector = startDay..endDay
    days_bucket = cut(days_vector, 30)
    ret_matrix_list = []
    for (days in days_bucket){{
        s_day = min(days)
        e_day = max(days)
        ret_matrix = get_ret_matrix(s_day, e_day, stock_vector)
        ret_matrix = select * from ret_matrix where Bartime in (09:30:00, 09:59:00, 10:29:00, 10:59:00, 11:29:00, 13:29:00, 13:59:00, 14:29:00, 14:59:00)
        ret_matrix_list.append!(ret_matrix)
    }}
    ret_matrix = unionAll(ret_matrix_list,false)
    ret_matrix = select * from ret_matrix order by Symbol,Date,Bartime
    share ret_matrix as {share_name}
    '''

    s.run(sql_script)
    
    s.close()






